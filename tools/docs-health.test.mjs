// Tests for tools/docs-health.mjs. Run: node --test tools/docs-health.test.mjs
//
// Every detector is proven to FIRE and to stay quiet on its near miss; every ratchet rule is proven both ways on a
// pure measurement; and the CLI is driven end to end in a throwaway git repository: --ratchet exits 0 on the
// baselined tree, 1 when a new page passes the cap, a page gains a history note or a hub page loses its header.

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync, spawnSync } from 'node:child_process';
import { copyFileSync, mkdtempSync, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
    CAP, GROW_ALLOWANCE, LEDGER_CAP, baselineOf, drift, editionTables, evaluate, frontmatter, headerProblems,
    historyNotes, isGenerated, ledgerBytes, measure,
} from './docs-health.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const HUB = 'docs/okf/product/module/x/spec-x.md';
const HEAD = '---\ntype: Spec\ntitle: X\ndescription: d\n---\n';
const FULL = '---\ntype: Spec\ntitle: X\ndescription: d\nitem: module.x\naudience: internal\nstatus: current\nverified: 2026-11-01 last-edit\ncode: x\n---\n';
const m = (files, tracked = () => true) => measure(Object.keys(files), (p) => files[p], tracked);

test('history notes: the four shapes count, a near miss does not, a fenced quote does not', () => {
    assert.equal(historyNotes('corrected 2026-11-12 · (was Personal) · refreshed 2026-10-01 · re-verified 2026-10-02'), 4);
    assert.equal(historyNotes('the corrected value · was 5 · until the end'), 0);
    assert.equal(historyNotes('```\ncorrected 2026-11-12\n```\n'), 0);
});

test('edition tables: a Basic | Standard | Advanced header row counts, bold or not; prose does not', () => {
    assert.equal(editionTables('| | **Basic** | **Standard** | **Advanced** |\n|---|---|---|---|'), 1);
    assert.equal(editionTables('| Feature | Basic | Standard | Advanced | Preview |'), 1);
    assert.equal(editionTables('Basic, Standard and Advanced editions'), 0);
    assert.equal(editionTables('| Basic | Advanced | Standard |'), 0);
});

test('frontmatter: scalars, inline lists and dash lists; none without the opening fence', () => {
    const fm = frontmatter('---\ntitle: "A"\ntags: [a, b]\ncode:\n  - tools/x.mjs\n  - inspecto/src\n---\nbody');
    assert.deepEqual(fm, { title: 'A', tags: ['a', 'b'], code: ['tools/x.mjs', 'inspecto/src'] });
    assert.equal(frontmatter('# no header\n---\n'), null);
});

test('header problems: only the new fields are validated, and only when present', () => {
    const tracked = (p) => p === 'tools/x.mjs';
    assert.deepEqual(headerProblems({ title: 'x' }, tracked), []);
    assert.equal(headerProblems({ audience: 'public' }, tracked).length, 1);
    assert.equal(headerProblems({ verified: 'yesterday' }, tracked).length, 1);
    assert.deepEqual(headerProblems({ audience: 'internal', verified: '2026-11-19 by review', code: ['tools/x.mjs'] }, tracked), []);
    assert.equal(headerProblems({ code: ['tools/gone.mjs'] }, tracked).length, 1);
});

test('generated pages: hub index.md, feature-db.md and a "generated by tools/" banner', () => {
    assert.ok(isGenerated('docs/okf/product/module/x/index.md', ''));
    assert.ok(isGenerated('docs/okf/product/module/x/feature-db.md', ''));
    assert.ok(isGenerated('docs/EDITIONS-matrix.md', '# t\n<!-- generated by tools/render-x.mjs -->'));
    // the two banner spellings the real generators write (tests inventory, api routes)
    assert.ok(isGenerated(HUB, HEAD + '# T\n\n> **Generated** by `tools/render-tests-inventory.mjs` from the sources'));
    assert.ok(isGenerated(HUB, HEAD + '# R\n> **GENERATED** by `tools/render-api-routes.mjs` from the routes'));
    assert.ok(isGenerated(HUB, HEAD + '# C\n> **Generated by `node tools/gen-la-demo-scripts.mjs` from the cases.**'));
    // prose that names a generator, and a banner far below the opening lines, are not banners
    assert.ok(!isGenerated(HUB, HEAD + 'The table is generated by `tools/x.mjs` nightly.'));
    assert.ok(!isGenerated(HUB, HEAD + '\n'.repeat(20) + '> **Generated** by `tools/x.mjs`'));
    assert.ok(!isGenerated(HUB, HEAD));
});

test('a generated page is never ratcheted, however large it grows (tests inventory)', () => {
    const inv = 'docs/okf/product/module/engine/tests-inventory.md';
    const text = HEAD + '> **Generated** by `tools/render-tests-inventory.mjs`\n' + 'row\n'.repeat(CAP / 4);
    assert.deepEqual(baselineOf(m({ [inv]: text })).oversize, {});
    assert.deepEqual(evaluate(m({ [inv]: text + 'row\n'.repeat(5000) }), baselineOf(m({}))).failures, []);
});

test('history: "valid until 2026-12-31" is a current fact, not a history note', () => {
    assert.equal(historyNotes('the licence is valid until 2026-12-31'), 0);
});

test('ledger bytes: the span between the count line and "## Area index"', () => {
    const board = 'x\n> **1<!--count:backlog-rows--> rows**\n> ⬆ entry\n\n## Area index\nrows';
    assert.equal(ledgerBytes(board), Buffer.byteLength('> ⬆ entry\n'));
    assert.equal(ledgerBytes('no anchors'), null);
});

test('size ratchet: a new page over the cap fails; a baselined one may grow by the allowance only', () => {
    const big = HEAD + 'x'.repeat(CAP);
    const base = baselineOf(m({ [HUB]: big }));
    assert.deepEqual(evaluate(m({ [HUB]: big }), base).failures, []);
    assert.deepEqual(evaluate(m({ [HUB]: big + 'y'.repeat(GROW_ALLOWANCE) }), base).failures, []);
    assert.equal(evaluate(m({ [HUB]: big + 'y'.repeat(GROW_ALLOWANCE + 10) }), base).failures.length, 1);
    const other = 'docs/okf/product/module/x/spec-y.md';
    assert.equal(evaluate(m({ [HUB]: big, [other]: FULL + 'x'.repeat(CAP) }), base).failures.length, 1);
});

test('size ratchet: the board, the glossary and in-flight plans are reported, never ratcheted', () => {
    const big = 'x'.repeat(CAP + 5000);
    const files = { 'docs/GLOSSARY.md': big, 'docs/superpower/p.md': big };
    assert.deepEqual(baselineOf(m(files)).oversize, {});
    assert.deepEqual(evaluate(m(files), baselineOf(m({}))).failures, []);
});

test('history ratchet: a rise fails, a fall improves; exempt pages and plans never fail', () => {
    const base = baselineOf(m({ [HUB]: HEAD + 'corrected 2026-11-01' }));
    assert.equal(evaluate(m({ [HUB]: HEAD + 'corrected 2026-11-01 (was old)' }), base).failures.length, 1);
    const fell = evaluate(m({ [HUB]: HEAD + 'now current' }), base);
    assert.deepEqual(fell.failures, []);
    assert.equal(fell.improvements.length, 1);
    const exempt = { 'docs/GLOSSARY.md': '(was Flow)', 'docs/superpower/p.md': 'corrected 2026-11-19' };
    assert.deepEqual(evaluate(m(exempt), baselineOf(m({}))).failures, []);
});

test('header ratchet: a new hub page without a header fails; a baselined one passes; a fix improves', () => {
    const base = baselineOf(m({ [HUB]: '# no header' }));
    assert.deepEqual(base.headerless, [HUB]);
    assert.deepEqual(evaluate(m({ [HUB]: '# no header' }), base).failures, []);
    assert.equal(evaluate(m({ [HUB]: '# no header', 'docs/okf/product/module/x/spec-z.md': '# none' }), base).failures.length, 1);
    assert.equal(evaluate(m({ [HUB]: HEAD }), base).improvements.length, 1);
    assert.deepEqual(evaluate(m({ 'docs/USER_GUIDE.md': '# root canon needs no header' }), baselineOf(m({}))).failures, []);
});

test('full-header ratchet: a new hub page needs the full header, a full page may not lose it, baselined debt passes', () => {
    const other = 'docs/okf/product/module/x/spec-y.md';
    const base = baselineOf(m({ [HUB]: HEAD, [other]: FULL }));
    assert.deepEqual(base.partialHeader, [HUB]);
    assert.deepEqual(evaluate(m({ [HUB]: HEAD, [other]: FULL }), base).failures, []);
    const lost = evaluate(m({ [HUB]: HEAD, [other]: HEAD }), base).failures;
    assert.equal(lost.length, 1, 'a full page that loses a field fails');
    assert.match(lost[0], /missing: item, audience, status, verified, code\) — run node tools\/fill-doc-headers\.mjs --write --hub module\/x/);
    const added = evaluate(m({ [HUB]: HEAD, [other]: FULL, 'docs/okf/product/module/x/spec-new.md': HEAD }), base).failures;
    assert.equal(added.length, 1, 'a new page with only the base header fails');
    assert.equal(evaluate(m({ [HUB]: FULL, [other]: FULL }), base).improvements.length, 1, 'a filled page improves');
    // a page baselined headerless that gains only the base header is progress, not new debt
    const headerless = baselineOf(m({ [HUB]: '# none' }));
    assert.deepEqual(evaluate(m({ [HUB]: HEAD }), headerless).failures, []);
    assert.deepEqual(evaluate(m({ 'docs/USER_GUIDE.md': HEAD }), baselineOf(m({}))).failures, [], 'root canon is not a hub page');
});

test('full-header ratchet: a layer page needs every field but code; losing one still fails', () => {
    const layer = 'docs/okf/product/layer/platform/spec-new.md';
    const noCode = FULL.replace('code: x\n', '');
    assert.deepEqual(evaluate(m({ [layer]: noCode }), baselineOf(m({}))).failures, [], 'a new layer page without code passes');
    const base = baselineOf(m({ [layer]: noCode }));
    assert.deepEqual(base.partialHeader, []);
    const lost = evaluate(m({ [layer]: noCode.replace(/verified: .*\n/, '') }), base).failures;
    assert.equal(lost.length, 1);
    assert.match(lost[0], /missing: verified\)/);
    assert.equal(evaluate(m({ [HUB]: noCode }), baselineOf(m({}))).failures.length, 1, 'a module page still needs code');
});

test('editions ratchet: a new hand-written table fails outside its homes, never inside them', () => {
    const table = '| | Basic | Standard | Advanced |\n';
    assert.equal(evaluate(m({ [HUB]: HEAD + table }), baselineOf(m({ [HUB]: HEAD }))).failures.length, 1);
    assert.deepEqual(evaluate(m({ 'docs/EDITIONS.md': table + table }), baselineOf(m({}))).failures, []);
});

test('ledger cap: over 60 KB fails with the roll command', () => {
    const board = '> **1<!--count:backlog-rows--> rows**\n' + ('> ⬆ x\n'.repeat(Math.ceil(LEDGER_CAP / 6) + 10)) + '## Area index\n';
    const f = evaluate(m({ 'docs/BACKLOG.md': board }), baselineOf(m({}))).failures;
    assert.equal(f.length, 1);
    assert.match(f[0], /roll-backlog-ledger/);
});

test('stale baseline entries are reported, never failed; generated pages are exempt', () => {
    const r = evaluate(m({ 'docs/okf/product/module/x/index.md': 'x'.repeat(CAP + 9000) }), { oversize: { 'docs/gone.md': 1 }, history: {}, headerless: [], editions: {} });
    assert.deepEqual(r.failures, []);
    assert.deepEqual(r.stale, ['docs/gone.md']);
});

test('drift: a page whose code changed after its verified date is listed', () => {
    const files = { [HUB]: '---\ntype: S\ntitle: t\ndescription: d\nverified: 2026-11-01\ncode: [tools/a.mjs, tools/b.mjs]\n---\n' };
    const d = drift(m(files), (p) => (p === 'tools/a.mjs' ? '2026-11-10' : '2026-10-01'));
    assert.deepEqual(d.map((x) => x.code), ['tools/a.mjs']);
});

test('CLI: --ratchet passes on the baselined tree and fails on new debt (throwaway repo)', () => {
    const dir = mkdtempSync(join(tmpdir(), 'docs-health-'));
    try {
        mkdirSync(join(dir, 'tools'));
        copyFileSync(join(HERE, 'docs-health.mjs'), join(dir, 'tools', 'docs-health.mjs'));
        const put = (p, t) => { mkdirSync(dirname(join(dir, p)), { recursive: true }); writeFileSync(join(dir, p), t); };
        for (let i = 0; i < 305; i++) put(`docs/okf/product/module/m${i}/spec-m${i}.md`, HEAD + 'body');
        const git = (...a) => execFileSync('git', a, { cwd: dir, encoding: 'utf8' });
        git('init', '-q'); git('add', '-A');
        const run = (...a) => spawnSync(process.execPath, [join(dir, 'tools', 'docs-health.mjs'), ...a], { cwd: dir, encoding: 'utf8' });
        assert.equal(run('--baseline-write').status, 0);
        assert.equal(run('--ratchet').status, 0, 'a baselined tree passes');
        put('docs/okf/product/module/m0/spec-m0.md', HEAD + 'x'.repeat(CAP + 10)); git('add', '-A');
        assert.equal(run('--ratchet').status, 1, 'a page that passes the cap fails');
        put('docs/okf/product/module/m0/spec-m0.md', HEAD + 'body corrected 2026-11-19'); git('add', '-A');
        assert.equal(run('--ratchet').status, 1, 'a new history note fails');
        put('docs/okf/product/module/m0/spec-m0.md', '# header gone'); git('add', '-A');
        assert.equal(run('--ratchet').status, 1, 'a hub page that loses its header fails');
        put('docs/okf/product/module/m0/spec-m0.md', HEAD + 'body'); git('add', '-A');
        assert.equal(run('--ratchet').status, 0, 'back to the baseline passes');
    } finally {
        rmSync(dir, { recursive: true, force: true });
    }
});
