#!/usr/bin/env node
// Renders the OFFERINGS MATRIX block of docs/EDITIONS.md - everything about editions that is a pure function of
// offerings/*.toon + the module manifests + tools/bundle-modules.mjs / tools/offering-classpath.mjs (docs/okf/backend/module-taxonomy.md; was: module-architecture plan
// §2.3 "the bundle generator, the EDITIONS matrix and the SBOM are generated from Offerings", §6 P6b).
//
//   node tools/render-offerings-matrix.mjs --write    rewrite the block between the markers
//   node tools/render-offerings-matrix.mjs --check    exit 1 when the block is stale (CI-friendly)
//
// WHAT IS GENERATED: a MODULE x EDITION matrix, an ADD-ON table, the DEPLOYMENT POSTURE table and a per-edition jar count.
// WHAT STAYS HAND-AUTHORED: every other EDITIONS row (transport, secrets, compliance, HA, capability CP-* rows). The SP-* rows
// stay owned by render-processor-board.mjs. Never hand-edit inside the markers - fix the Offering or the manifest instead.
import { readFileSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { EDITIONS, bundleModules, coreModules } from './bundle-modules.mjs';
import { classpath, resolveOffering } from './offering-classpath.mjs';
import { gather, parseToon, POSTURE } from './check-offerings.mjs';

export const BEGIN = '<!-- offerings-matrix:begin -->';
export const END = '<!-- offerings-matrix:end -->';
const LAYERS = ['spi', 'platform', 'features', 'la', 'providers', 'inspecto'];
const cell = (s) => String(s).replace(/\|/g, '\\|');

/** Offering id -> its add-ons with inherited ones merged (the including Offering's status wins), as check-offerings does. */
function resolveAddons(offerings, id) {
    const o = offerings[id];
    const out = {};
    for (const inc of o.includes ?? []) Object.assign(out, resolveAddons(offerings, inc));
    for (const [k, v] of Object.entries(o.addons ?? {})) {
        const prev = out[k] ?? {};
        out[k] = { ...prev, ...v, modules: [...new Set([...(prev.modules ?? []), ...(v.modules ?? [])])] };
    }
    return out;
}

/** The generated markdown (no markers), LF line endings. */
export function render(root, g = gather(root)) {
    const layerOf = {};
    for (const f of execFileSync('git', ['ls-files', '*META-INF/inspecto/module.toon'], { cwd: root, encoding: 'utf8' }).split('\n').filter(Boolean)) {
        layerOf[parseToon(readFileSync(join(root, f), 'utf8')).id] = f.split('/')[0];
    }
    const shipped = {};
    for (const e of EDITIONS) shipped[e] = resolveOffering(e, g);
    const L = [];
    L.push('> Generated by `tools/render-offerings-matrix.mjs` from `offerings/*.toon`, the module manifests and `tools/bundle-modules.mjs` -');
    L.push('> **do not hand-edit**; fix the Offering or the manifest and run `node tools/render-offerings-matrix.mjs --write`.');
    L.push('> Cells: ✅ the edition stages it · — absent · 🟦 base (always present: shaded into the processor jar or a core thin jar).');
    L.push('');
    L.push('### Modules by edition');
    L.push('');
    L.push(`| Module | Layer | Role | Requires | ${EDITIONS.join(' | ')} |`);
    L.push(`|---|---|---|---|${EDITIONS.map(() => ':-:').join('|')}|`);
    const ids = Object.keys(g.manifests).sort((a, b) =>
        LAYERS.indexOf(layerOf[a]) - LAYERS.indexOf(layerOf[b]) || a.localeCompare(b));
    for (const id of ids) {
        const m = g.manifests[id];
        const always = ['base', 'internal'].includes(m.offeringRole);
        const cells = EDITIONS.map((e) => (always ? '🟦' : shipped[e].has(id) ? '✅' : '—'));
        L.push(`| \`${id}\` - ${cell(m.title ?? '')} | ${layerOf[id]} | ${m.offeringRole} | ${(m.requires?.modules ?? []).map((r) => `\`${r}\``).join(', ') || '—'} | ${cells.join(' | ')} |`);
    }
    L.push('');
    L.push('### Add-ons by edition');
    L.push('');
    L.push(`| Add-on | Modules / hosted by | ${EDITIONS.join(' | ')} |`);
    L.push(`|---|---|${EDITIONS.map(() => ':-:').join('|')}|`);
    const perEdition = Object.fromEntries(EDITIONS.map((e) => [e, resolveAddons(g.offerings, e.toLowerCase())]));
    const names = [...new Set(EDITIONS.flatMap((e) => Object.keys(perEdition[e])))].sort();
    for (const n of names) {
        const any = EDITIONS.map((e) => perEdition[e][n]).find(Boolean);
        const mods = (any.modules?.length ? any.modules : any.hostedBy ?? []).map((x) => `\`${x}\``).join(', ');
        L.push(`| ${n} | ${any.status === 'planned' ? 'planned in ' : ''}${mods} | ${EDITIONS.map((e) => perEdition[e][n]?.status ?? '—').join(' | ')} |`);
    }
    L.push('');
    L.push('### Deployment posture');
    L.push('');
    L.push(`| Posture | ${EDITIONS.join(' | ')} |`);
    L.push(`|---|${EDITIONS.map(() => ':-:').join('|')}|`);
    for (const k of Object.keys(POSTURE)) L.push(`| ${k} | ${EDITIONS.map((e) => g.offerings[e.toLowerCase()].posture?.[k] ?? '—').join(' | ')} |`);
    L.push('');
    L.push('### Staged jars');
    L.push('');
    L.push(`| | ${EDITIONS.join(' | ')} |`);
    L.push(`|---|${EDITIONS.map(() => ':-:').join('|')}|`);
    const first = (e) => bundleModules(e).length + coreModules().length;
    L.push(`| First-party jars (processor + connectors + optional + core thin) | ${EDITIONS.map(first).join(' | ')} |`);
    L.push(`| of which core thin jars | ${EDITIONS.map(() => coreModules().length).join(' | ')} |`);
    L.push(`| Optional modules beyond Personal | ${EDITIONS.map((e) => bundleModules(e).length - bundleModules('Personal').length).join(' | ')} |`);
    L.push(`| Total on the classpath (+ third-party sidecars) | ${EDITIONS.map((e) => classpath(e, { g }).length).join(' | ')} |`);
    return L.join('\n');
}

/** Replaces the text between the markers; throws when a marker is missing or duplicated. */
export function splice(doc, body) {
    const eol = doc.includes('\r\n') ? '\r\n' : '\n';
    const lf = doc.replace(/\r\n/g, '\n');
    const b = lf.indexOf(BEGIN), e = lf.indexOf(END);
    if (b < 0 || e < b || lf.indexOf(BEGIN, b + 1) >= 0 || lf.indexOf(END, e + 1) >= 0) throw new Error(`docs/EDITIONS.md must carry exactly one ${BEGIN} ... ${END} pair`);
    return (lf.slice(0, b + BEGIN.length) + '\n' + body + '\n' + lf.slice(e)).replace(/\n/g, eol);
}

function main() {
    const root = join(dirname(fileURLToPath(import.meta.url)), '..');
    const file = join(root, 'docs/EDITIONS.md');
    const a = process.argv.slice(2);
    if (!a.includes('--check') && !a.includes('--write')) { console.error('usage: render-offerings-matrix.mjs --check | --write'); process.exit(2); }
    const doc = readFileSync(file, 'utf8');
    let next;
    try { next = splice(doc, render(root)); } catch (e) { console.error(`render-offerings-matrix: ${e.message}`); process.exit(2); }
    if (next === doc) { console.log('render-offerings-matrix: docs/EDITIONS.md is current'); return; }
    if (a.includes('--write')) { writeFileSync(file, next); console.log('render-offerings-matrix: rewrote the block in docs/EDITIONS.md'); return; }
    console.error('render-offerings-matrix: the offerings-matrix block in docs/EDITIONS.md is stale - run: node tools/render-offerings-matrix.mjs --write');
    process.exit(1);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
