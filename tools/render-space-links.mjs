#!/usr/bin/env node
// Renders the "Every link and what protects it" table (§12.2) of
// docs/okf/product/module/config/architecture-space-anatomy.md from the link census,
// platform/inspecto-engine/src/main/java/com/gamma/pipeline/LinkCensus.java (`SPACE-LINK-CENSUS-1` LC-7).
// ONE list of links, two readers: every check reads the census, the page reads this. Add or change a link in
// LinkCensus.LINKS, run this; never hand-edit the rows between the markers.
//
//   node tools/render-space-links.mjs            # rewrite the table in place
//   node tools/render-space-links.mjs --check    # exit 1 when the page is stale (CI guards job)
//
// The census is parsed from the source (the way tools/check-space-anatomy.mjs parses its constants), not run:
// every `link("from", "key", "to", Type.X, ONDELETE, ONRENAME, CHECKS...)` line inside `LINKS = List.of(`.
// The parse fails loudly when it reads no link, or when a line starting `link(` does not match the shape.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const CENSUS = 'platform/inspecto-engine/src/main/java/com/gamma/pipeline/LinkCensus.java';
const PAGE = 'docs/okf/product/module/config/architecture-space-anatomy.md';
const BEGIN = '<!-- link-census:begin (generated by tools/render-space-links.mjs from LinkCensus.LINKS; do not edit) -->';
const END = '<!-- link-census:end -->';

/** The census links, in declaration order. */
export function parseCensus(src) {
    const start = src.indexOf('LINKS = List.of(');
    if (start < 0) throw new Error(`${CENSUS}: no "LINKS = List.of(" — the render's anchor moved`);
    const body = src.slice(start, src.indexOf('));', start) + 2);
    const links = [];
    for (const raw of body.split('\n')) {
        const line = raw.replace(/\/\/.*$/, '').trim();
        if (!line.startsWith('link(')) continue;
        const m = line.match(/^link\("([^"]+)",\s*"([^"]+)",\s*"([^"]+)",\s*Type\.([A-Z_]+),\s*([A-Z]+),\s*([A-Z]+)((?:,\s*[A-Z]+)*)\)/);
        if (!m) throw new Error(`${CENSUS}: a link line the render cannot read: ${line}`);
        const checks = m[7].split(',').map((s) => s.trim()).filter(Boolean);
        links.push({ from: m[1], key: m[2], to: m[3], type: m[4], onDelete: m[5], onRename: m[6], checks });
    }
    if (links.length === 0) throw new Error(`${CENSUS}: read no link — the render's parse broke`);
    return links;
}

// Canonical display names (docs/GLOSSARY.md); an unknown kind shows as its census id.
const KIND = {
    pipeline: 'Pipeline', enrichment: 'Enrichment', job: 'Job', expectation: 'Expectation',
    'decision-rule': 'Decision Rule', dataset: 'Dataset', 'alert-rule': 'Alert Rule', widget: 'Widget',
    dashboard: 'Dashboard', 'link-analysis-view': 'Link Analysis view', 'geo-map-view': 'Geo Map view',
    reconciliation: 'Reconciliation', query: 'Query', 'nav-menu': '`nav-menus.toon`',
    'schema-file': '`*_schema.toon` file', component: 'registry component', connection: 'Connection',
    store: 'store', file: 'file', 'job-template': '`*_job_template.toon`', 'pipeline-file': '`*_pipeline.toon` file',
    directory: 'directory', signal: 'signal', column: 'column',
};
const TYPE = {
    ID: 'id', ID_LIST: 'id, or a comma list of ids', PATH: 'path', STORE: 'store name', COLUMN: 'column name',
    SQL_RELATION: 'SQL relation', SQL_COLUMN: 'SQL column', TEXT: 'text',
};
const CHECK = { LOAD: 'load', DELETE: 'delete 409', RENAME: 'rename', IMPACT: 'impact', VALIDATE: 'validate', IMPORT: 'import' };
const CHECK_ORDER = ['LOAD', 'DELETE', 'RENAME', 'IMPACT', 'VALIDATE', 'IMPORT'];
const kind = (k) => KIND[k] ?? `\`${k}\``;

export function renderTable(links) {
    const rows = links.map((l) => {
        const checks = CHECK_ORDER.filter((c) => l.checks.includes(c)).map((c) => CHECK[c] ?? c.toLowerCase());
        return `| ${kind(l.from)} | \`${l.key}\` | ${kind(l.to)} | ${TYPE[l.type] ?? l.type} | `
            + `${l.onDelete.toLowerCase()} | ${l.onRename.toLowerCase()} | ${checks.length ? checks.join(', ') : '**none**'} |`;
    });
    return [BEGIN,
        '| From | Key | To | Value | On delete | On rename | Checked by today |',
        '|---|---|---|---|---|---|---|',
        ...rows, END].join('\n');
}

/** The page with the generated block replaced; throws when the markers are missing or out of order. */
export function splice(page, table) {
    const a = page.indexOf(BEGIN), b = page.indexOf(END);
    if (a < 0 || b < a) throw new Error(`${PAGE}: the link-census markers are missing — restore them in §12.2`);
    return page.slice(0, a) + table + page.slice(b + END.length);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
    const links = parseCensus(readFileSync(join(root, CENSUS), 'utf8'));
    const page = readFileSync(join(root, PAGE), 'utf8');
    const next = splice(page, renderTable(links));
    if (process.argv.includes('--check')) {
        if (next !== page) {
            console.error(`✖ ${PAGE} §12.2 is stale against LinkCensus.LINKS — run: node tools/render-space-links.mjs`);
            process.exit(1);
        }
        console.log(`✓ Space link table: ${links.length} census link(s) rendered in ${PAGE} §12.2, up to date.`);
    } else {
        if (next !== page) writeFileSync(join(root, PAGE), next);
        console.log(`${next !== page ? 'wrote' : 'unchanged'}: ${PAGE} §12.2 (${links.length} census links)`);
    }
}
