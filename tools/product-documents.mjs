// product-documents — the generated documents of each Product's hub (PRODUCT-ASSEMBLY-1 PA-10d; plan
// docs/superpower/2026-11-10-product-assembly-plan.md §10 and §11 PA-10, decision D-PA36). Called by tools/render-product-docs.mjs,
// which writes them (and `--check` holds them current) before it draws the hub tables.
//
// For each Product (products/<id>.toon) four files in docs/okf/product/product/<id>/, composed from the Product definition, its
// Apps (apps/<id>/app.toon), their Add-ons and the Editions, linking into those items' own hubs:
//   brochure.md     what it is, its Apps with what each does, the Add-ons, Editions and Distributions
//   features.md     the datasheet: each App's version, Add-ons and Space Templates, and which Apps each Edition can carry
//   user-guide.md   per App, the user guides its templates' and Add-ons' hubs hold
//   admin-guide.md  installing and licensing (entitlements, live App install, operations), then per App the admin guides
// A file of one of those slots in a Product hub that is not generated is refused (one source per slot). Demo and video scripts
// are not generated (the demo script is products/<id>.demo-build.txt).

import { existsSync, readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';
import { addonModules, builtAddons, gatherModel, productApps } from './products.mjs';
import { parseToon } from './toon-subset.mjs';

export const GENERATED_SLOTS = ['brochure', 'features', 'user-guide', 'admin-guide'];
export const MARK = '<!-- generated by tools/render-product-docs.mjs from products/';
const list = (x) => (Array.isArray(x) ? x : []);

/** Throws when a Product hub folder holds a file of a generated slot that this tool did not write (one source per slot). */
export function refuseHandWritten(dir, id) {
    if (!existsSync(dir)) return;
    for (const f of readdirSync(dir).filter((n) => n.endsWith('.md'))) {
        const slot = GENERATED_SLOTS.find((s) => f === `${s}.md` || f.startsWith(`${s}-`));
        if (slot && (f !== `${slot}.md` || !readFileSync(join(dir, f), 'utf8').includes(MARK)))
            throw new Error(`${join(dir, f)}: the ${slot} slot of a Product hub is generated (D-PA36) - change products/${id}.toon or the hubs it links, not this file`);
    }
}

/** Every generated Product document: { 'docs/okf/product/product/<id>/<slot>.md': text }. Throws on a hand-written file in a generated slot. */
export function productDocuments(root) {
    const model = gatherModel(root);
    const items = (kind) => {
        const dir = join(root, 'product-map', kind);
        return existsSync(dir) ? Object.fromEntries(readdirSync(dir).filter((f) => f.endsWith('.toon')).map((f) => [f.slice(0, -5), parseToon(readFileSync(join(dir, f), 'utf8'))])) : {};
    };
    const addonItems = Object.fromEntries(Object.entries(items('addon')).map(([n, it]) => [it.offeringAddon ?? n, { name: n, title: it.title ?? n }]));
    const editionItems = items('edition');
    const packItems = Object.fromEntries(Object.entries(items('solution-pack')).filter(([, it]) => it.template).map(([n, it]) => [it.template, { name: n, title: it.title ?? n }]));
    const hubDir = (kind, name) => join(root, 'docs', 'okf', 'product', kind, name);
    const hubFiles = (kind, name, slot) => (existsSync(hubDir(kind, name)) ? readdirSync(hubDir(kind, name)).filter((f) => f === `${slot}.md` || (f.startsWith(`${slot}-`) && f.endsWith('.md'))).sort() : []);
    const titleIn = (kind, name, f) => {
        const t = readFileSync(join(hubDir(kind, name), f), 'utf8');
        return (/^title:\s*(.+)$/m.exec(t)?.[1] ?? /^#\s+(.+)$/m.exec(t)?.[1] ?? f).trim().replace(/^["']|["']$/g, '');
    };
    const link = (kind, name, f = 'index.md') => `../../${kind}/${name}/${f}`;
    const addonLink = (a) => (addonItems[a] ? `[${addonItems[a].title}](${link('addon', addonItems[a].name)})` : `\`${a}\``);
    const packLink = (t) => (packItems[t] ? `[${packItems[t].title}](${link('solution-pack', packItems[t].name)})` : `\`${t}\``);
    const editionLink = (e) => (editionItems[e] ? `[${editionItems[e].title ?? e}](${link('edition', e)})` : e);
    const appLink = (a) => `[${model.apps[a]?.title ?? a}](${link('app', a)})`;
    const out = {};

    for (const [id, p] of Object.entries(model.products)) {
        const dir = join(root, 'docs', 'okf', 'product', 'product', id);
        refuseHandWritten(dir, id);
        const { required, optional } = productApps(p);
        const apps = [...required, ...optional].filter((a) => model.apps[a]);
        const addonsOf = (a) => list(model.apps[a]?.requires?.addons);
        const addons = p.shape === 'platform' ? list(p.addons) : [...new Set(apps.flatMap(addonsOf))];
        const templatesOf = (a) => list(model.apps[a]?.templates);
        const name = p.brand?.name ?? p.title;
        const editions = list(p.editions);
        const head = (heading, audience) => [
            `# ${name} — ${heading}`, '',
            `${MARK}${id}.toon and the hubs it links; never edit it: change the definition or those hubs, then run the tool -->`, '',
            `*Audience: ${audience}. Product Map Item [\`product.${id}\`](index.md) · ${p.shape === 'domain' ? 'a Domain product' : 'a Platform product'}${p.industry ? ` for the ${model.industries[p.industry]?.title ?? p.industry} Industry` : ''}.*`, '',
        ];
        // An App's guides of one slot: those in the hubs of its Space Templates, of its Add-ons, and of the modules those
        // Add-ons hold (an Add-on hub points there), each listed once.
        const modulesOf = (x) => [...new Set(editions.filter((e) => model.offerings[e]).flatMap((e) => [...addonModules(e, x, model.offerings)]))].sort();
        const entries = (kind, n, slot) => hubFiles(kind, n, slot).map((f) => `[${titleIn(kind, n, f)}](${link(kind, n, f)})`);
        const guides = (a, slot) => [...new Set([
            ...templatesOf(a).map((t) => packItems[t]?.name).filter(Boolean).flatMap((n) => entries('solution-pack', n, slot)),
            ...addonsOf(a).map((x) => addonItems[x]?.name).filter(Boolean).flatMap((n) => entries('addon', n, slot)),
            ...addonsOf(a).flatMap(modulesOf).flatMap((m) => entries('module', m, slot)),
        ])];
        const role = (a) => (required.includes(a) ? 'required' : 'optional');

        // brochure
        const blurbs = (a) => Object.values(model.apps[a]?.nav && typeof model.apps[a].nav === 'object' ? model.apps[a].nav : {}).map((n) => n.blurb).filter(Boolean);
        out[`docs/okf/product/product/${id}/brochure.md`] = [
            ...head('brochure', 'customers, presales and sales. Prices are not published here'),
            ...(p.brand?.tagline ? [`> **${p.brand.tagline}**`, ''] : []),
            '## What it is', '',
            p.brand?.signInBody ?? (p.shape === 'platform'
                ? `${name} is the Inspecto Platform with the Add-ons you choose, for teams that build their own Pipelines, Apps and controls.`
                : `${name} is one Industry's finished Apps on one Inspecto Platform.`), '',
            '## Apps', '',
            ...(apps.length ? apps.map((a) => `- **${appLink(a)}** (${role(a)})${blurbs(a).length ? ` — ${blurbs(a).join(' ')}` : ''}`) : ['No Apps: the Platform product is used through the console.']), '',
            `## Add-ons${p.shape === 'platform' ? ' to choose from' : ' it brings'}`, '',
            addons.map(addonLink).join(' · ') || 'none', '',
            '## Editions and Distributions', '',
            `Editions: ${editions.map(editionLink).join(' · ')}. Distributions: ${list(p.distributions).join(', ')}.`, '',
            '## Read next', '',
            '- [Datasheet](features.md) · [User guide](user-guide.md) · [Admin guide](admin-guide.md)', '',
        ].join('\n');

        // datasheet
        const offered = Object.fromEntries(editions.map((e) => [e, model.offerings[e] ? builtAddons(e, model.offerings) : new Set()]));
        out[`docs/okf/product/product/${id}/features.md`] = [
            ...head('datasheet', 'presales, buyers and architects'),
            '## Apps', '',
            '| App | Version | Platform | Add-ons it needs | Space Templates |', '|---|---|---|---|---|',
            ...apps.map((a) => `| ${appLink(a)} (${role(a)}) | ${model.apps[a].version ?? ''} | ${(model.apps[a].platform ?? '').replace(/\|/g, '\\|')} | ${addonsOf(a).map(addonLink).join(', ') || '—'} | ${templatesOf(a).map(packLink).join(', ') || '—'} |`),
            ...(apps.length ? [] : ['| — | | | | |']), '',
            '## Which Apps each Edition can carry', '',
            `An App ships in an Edition when that Edition builds every Add-on the App needs.`, '',
            `| Edition | ${apps.map((a) => model.apps[a].title ?? a).join(' | ') || 'Apps'} |`, `|---|${apps.map(() => '---').join('|') || '---'}|`,
            ...editions.map((e) => `| ${editionLink(e)} | ${apps.map((a) => (addonsOf(a).every((x) => offered[e].has(x)) ? 'yes' : 'no')).join(' | ') || '—'} |`), '',
            ...(p.space ? [`The Apps' Space Templates are composed into one Space Template, \`${p.space}\`, over one ingest of the Industry's records.`, ''] : []),
            ...(p.shape === 'platform' && list(p.templates).length ? ['## Space Templates it ships', '', list(p.templates).map(packLink).join(' · '), ''] : []),
            `Distributions: ${list(p.distributions).join(', ')}.`, '',
        ].join('\n');

        // user guide
        // The Platform product is used through the console, whose own guides live in layer/product.
        const general = p.shape === 'platform' ? entries('layer', 'product', 'user-guide') : [];
        out[`docs/okf/product/product/${id}/user-guide.md`] = [
            ...head('user guide', 'analysts and the people who work the Apps every day'),
            ...(general.length ? ['## The console', '', ...general.map((x) => `- ${x}`), ''] : []),
            ...apps.flatMap((a) => {
                const g = guides(a, 'user-guide');
                return [`## ${model.apps[a].title ?? a}`, '', ...(g.length ? g.map((x) => `- ${x}`) : [`- No user guide in the hubs of this App's templates and Add-ons yet; see ${appLink(a)}.`]), ''];
            }),
        ].join('\n');

        // admin guide
        const platformGuides = ['admin-guide-entitlements.md', 'admin-guide-apps.md', 'admin-guide-operations.md', 'admin-guide-launch-flags.md']
            .filter((f) => existsSync(join(hubDir('layer', 'platform'), f)));
        out[`docs/okf/product/product/${id}/admin-guide.md`] = [
            ...head('admin guide', 'administrators who install, license and run it'),
            '## Install, licence and run', '',
            ...platformGuides.map((f) => `- [${titleIn('layer', 'platform', f)}](${link('layer', 'platform', f)})`),
            ...editions.map((e) => `- The ${editionLink(e)} Edition`), '',
            ...apps.flatMap((a) => {
                const g = guides(a, 'admin-guide');
                return [`## ${model.apps[a].title ?? a}`, '', ...(g.length ? g.map((x) => `- ${x}`) : [`- No admin guide in the hubs of this App's templates and Add-ons yet; see ${appLink(a)}.`]), ''];
            }),
        ].join('\n');
    }
    return out;
}
