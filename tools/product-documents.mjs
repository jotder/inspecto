// product-documents — the generated documents of each Product's hub (PRODUCT-ASSEMBLY-1 PA-10d; plan
// docs/superpower/2026-11-10-product-assembly-plan.md §10 and §11 PA-10, decision D-PA36). Called by tools/render-product-docs.mjs,
// which writes them (and `--check` holds them current) before it draws the hub tables.
//
// For each Product (products/<id>.toon) six files in docs/okf/product/product/<id>/, composed from the Product definition, its
// Apps (apps/<id>/app.toon), their Add-ons and the Editions, linking into those items' own hubs:
//   brochure.md     what it is, its Apps with what each does, the Add-ons, Editions and Distributions
//   features.md     the datasheet: each App's version, Add-ons and Space Templates, and which Apps each Edition can carry
//   user-guide.md   per App, the user guides its templates' and Add-ons' hubs hold
//   admin-guide.md  installing and licensing (entitlements, live App install, operations), then per App the admin guides
//   brochure-demo-script.md   the live demo: the demo Space, its Demo Users (from products/<id>.demo-build.txt), a walk-through
//                             of each App's pages, and the Alert Rules the demo Space's templates seed
//   brochure-video-script.md  one overview video in the beats of the hand-written series (module/la-core brochure-video-scripts.md)
// A file of one of those slots in a Product hub that is not generated is refused (one source per slot; PRODUCT-SCRIPTS-GENERATED-1).

import { existsSync, readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';
import { addonModules, appNav, builtAddons, demoTextOf, gatherModel, productApps, seedToolOf, spaceParts } from './products.mjs';
import { parseToon } from './toon-subset.mjs';

export const GENERATED_SLOTS = ['brochure', 'features', 'user-guide', 'admin-guide'];
/** Every generated file name (without .md): one per slot, plus the demo and video scripts, topics of the brochure slot. */
export const GENERATED_FILES = [...GENERATED_SLOTS, 'brochure-demo-script', 'brochure-video-script'];
export const MARK = '<!-- generated by tools/render-product-docs.mjs from products/';
const list = (x) => (Array.isArray(x) ? x : []);
/** The first sentence of a description, cut at a word near 160 characters when longer. */
const firstSentence = (text) => {
    const s = /^(.*?\.)\s/.exec(text)?.[1] ?? text;
    return s.length <= 160 ? s : `${s.slice(0, s.lastIndexOf(' ', 157))} …`;
};

/** Throws when a Product hub folder holds a file of a generated slot that this tool did not write (one source per slot). */
export function refuseHandWritten(dir, id) {
    if (!existsSync(dir)) return;
    for (const f of readdirSync(dir).filter((n) => n.endsWith('.md'))) {
        const slot = GENERATED_SLOTS.find((s) => f === `${s}.md` || f.startsWith(`${s}-`));
        if (slot && (!GENERATED_FILES.includes(f.slice(0, -3)) || !readFileSync(join(dir, f), 'utf8').includes(MARK)))
            throw new Error(`${join(dir, f)}: the ${slot} slot of a Product hub is generated (D-PA36) - change products/${id}.toon or the hubs it links, not this file`);
    }
}

/** Every generated Product document: { 'docs/okf/product/product/<id>/<slot>.md': text }. Throws on a hand-written file in a generated slot. */
export function productDocuments(root) {
    const model = gatherModel(root);
    const items = (kind) => {
        const dir = join(root, 'product-map', kind);
        return existsSync(dir) ? Object.fromEntries(readdirSync(dir).filter((f) => f.endsWith('.toon')).map((f) => [f.slice(0, -5), parseToon(readFileSync(join(dir, f), 'utf8'))])) : {};
    };
    const addonItems = Object.fromEntries(Object.entries(items('addon')).map(([n, it]) => [it.offeringAddon ?? n, { name: n, title: it.title ?? n }]));
    const editionItems = items('edition');
    const packItems = Object.fromEntries(Object.entries(items('solution-pack')).filter(([, it]) => it.template).map(([n, it]) => [it.template, { name: n, title: it.title ?? n }]));
    const hubDir = (kind, name) => join(root, 'docs', 'okf', 'product', kind, name);
    const hubFiles = (kind, name, slot) => (existsSync(hubDir(kind, name)) ? readdirSync(hubDir(kind, name)).filter((f) => f === `${slot}.md` || (f.startsWith(`${slot}-`) && f.endsWith('.md'))).sort() : []);
    const titleIn = (kind, name, f) => {
        const t = readFileSync(join(hubDir(kind, name), f), 'utf8');
        return (/^title:\s*(.+)$/m.exec(t)?.[1] ?? /^#\s+(.+)$/m.exec(t)?.[1] ?? f).trim().replace(/^["']|["']$/g, '');
    };
    const link = (kind, name, f = 'index.md') => `../../${kind}/${name}/${f}`;
    const addonLink = (a) => (addonItems[a] ? `[${addonItems[a].title}](${link('addon', addonItems[a].name)})` : `\`${a}\``);
    const packLink = (t) => (packItems[t] ? `[${packItems[t].title}](${link('solution-pack', packItems[t].name)})` : `\`${t}\``);
    const editionLink = (e) => (editionItems[e] ? `[${editionItems[e].title ?? e}](${link('edition', e)})` : e);
    const appLink = (a) => `[${model.apps[a]?.title ?? a}](${link('app', a)})`;
    const out = {};

    for (const [id, p] of Object.entries(model.products)) {
        const dir = join(root, 'docs', 'okf', 'product', 'product', id);
        refuseHandWritten(dir, id);
        const { required, optional } = productApps(p);
        const apps = [...required, ...optional].filter((a) => model.apps[a]);
        const addonsOf = (a) => list(model.apps[a]?.requires?.addons);
        const addons = p.shape === 'platform' ? list(p.addons) : [...new Set(apps.flatMap(addonsOf))];
        const templatesOf = (a) => list(model.apps[a]?.templates);
        const name = p.brand?.name ?? p.title;
        const editions = list(p.editions);
        const head = (heading, audience) => [
            `# ${name} — ${heading}`, '',
            `${MARK}${id}.toon and the hubs it links; never edit it: change the definition or those hubs, then run the tool -->`, '',
            `*Audience: ${audience}. Product Map Item [\`product.${id}\`](index.md) · ${p.shape === 'domain' ? 'a Domain product' : 'a Platform product'}${p.industry ? ` for the ${model.industries[p.industry]?.title ?? p.industry} Industry` : ''}.*`, '',
        ];
        // An App's guides of one slot: those in the hubs of its Space Templates, of its Add-ons, and of the modules those
        // Add-ons hold (an Add-on hub points there), each listed once.
        const modulesOf = (x) => [...new Set(editions.filter((e) => model.offerings[e]).flatMap((e) => [...addonModules(e, x, model.offerings)]))].sort();
        const entries = (kind, n, slot) => hubFiles(kind, n, slot).map((f) => `[${titleIn(kind, n, f)}](${link(kind, n, f)})`);
        const guides = (a, slot) => [...new Set([
            ...templatesOf(a).map((t) => packItems[t]?.name).filter(Boolean).flatMap((n) => entries('solution-pack', n, slot)),
            ...addonsOf(a).map((x) => addonItems[x]?.name).filter(Boolean).flatMap((n) => entries('addon', n, slot)),
            ...addonsOf(a).flatMap(modulesOf).flatMap((m) => entries('module', m, slot)),
        ])];
        const role = (a) => (required.includes(a) ? 'required' : 'optional');

        // brochure
        const whatItIs = p.brand?.signInBody ?? (p.shape === 'platform'
            ? `${name} is the Inspecto Platform with the Add-ons you choose, for teams that build their own Pipelines, Apps and controls.`
            : `${name} is one Industry's finished Apps on one Inspecto Platform.`);
        const blurbs = (a) => Object.values(model.apps[a]?.nav && typeof model.apps[a].nav === 'object' ? model.apps[a].nav : {}).map((n) => n.blurb).filter(Boolean);
        out[`docs/okf/product/product/${id}/brochure.md`] = [
            ...head('brochure', 'customers, presales and sales. Prices are not published here'),
            ...(p.brand?.tagline ? [`> **${p.brand.tagline}**`, ''] : []),
            '## What it is', '',
            whatItIs, '',
            '## Apps', '',
            ...(apps.length ? apps.map((a) => `- **${appLink(a)}** (${role(a)})${blurbs(a).length ? ` — ${blurbs(a).join(' ')}` : ''}`) : ['No Apps: the Platform product is used through the console.']), '',
            `## Add-ons${p.shape === 'platform' ? ' to choose from' : ' it brings'}`, '',
            addons.map(addonLink).join(' · ') || 'none', '',
            '## Editions and Distributions', '',
            `Editions: ${editions.map(editionLink).join(' · ')}. Distributions: ${list(p.distributions).join(', ')}.`, '',
            '## Read next', '',
            '- [Datasheet](features.md) · [User guide](user-guide.md) · [Admin guide](admin-guide.md)', '',
        ].join('\n');

        // datasheet
        const offered = Object.fromEntries(editions.map((e) => [e, model.offerings[e] ? builtAddons(e, model.offerings) : new Set()]));
        out[`docs/okf/product/product/${id}/features.md`] = [
            ...head('datasheet', 'presales, buyers and architects'),
            '## Apps', '',
            '| App | Version | Platform | Add-ons it needs | Space Templates |', '|---|---|---|---|---|',
            ...apps.map((a) => `| ${appLink(a)} (${role(a)}) | ${model.apps[a].version ?? ''} | ${(model.apps[a].platform ?? '').replace(/\|/g, '\\|')} | ${addonsOf(a).map(addonLink).join(', ') || '—'} | ${templatesOf(a).map(packLink).join(', ') || '—'} |`),
            ...(apps.length ? [] : ['| — | | | | |']), '',
            '## Which Apps each Edition can carry', '',
            `An App ships in an Edition when that Edition builds every Add-on the App needs.`, '',
            `| Edition | ${apps.map((a) => model.apps[a].title ?? a).join(' | ') || 'Apps'} |`, `|---|${apps.map(() => '---').join('|') || '---'}|`,
            ...editions.map((e) => `| ${editionLink(e)} | ${apps.map((a) => (addonsOf(a).every((x) => offered[e].has(x)) ? 'yes' : 'no')).join(' | ') || '—'} |`), '',
            ...(p.space ? [`The Apps' Space Templates are composed into one Space Template, \`${p.space}\`, over one ingest of the Industry's records.`, ''] : []),
            ...(list(p.templates).length ? ['## Space Templates it ships', '', list(p.templates).map(packLink).join(' · '), ''] : []),
            `Distributions: ${list(p.distributions).join(', ')}.`, '',
        ].join('\n');

        // The Space Templates a Product ships itself (not through an App), with the guides their hubs hold.
        const ownTemplates = list(p.templates);
        const ownTemplateGuides = (slot) => {
            const g = [...new Set(ownTemplates.map((t) => packItems[t]?.name).filter(Boolean).flatMap((n) => entries('solution-pack', n, slot)))];
            return g.length ? ['## The Space Templates it ships', '', ...g.map((x) => `- ${x}`), ''] : [];
        };

        // user guide
        // The Platform product is used through the console, whose own guides live in layer/product.
        const general = p.shape === 'platform' ? entries('layer', 'product', 'user-guide') : [];
        out[`docs/okf/product/product/${id}/user-guide.md`] = [
            ...head('user guide', 'analysts and the people who work the Apps every day'),
            ...(general.length ? ['## The console', '', ...general.map((x) => `- ${x}`), ''] : []),
            ...apps.flatMap((a) => {
                const g = guides(a, 'user-guide');
                return [`## ${model.apps[a].title ?? a}`, '', ...(g.length ? g.map((x) => `- ${x}`) : [`- No user guide in the hubs of this App's templates and Add-ons yet; see ${appLink(a)}.`]), ''];
            }),
            ...ownTemplateGuides('user-guide'),
        ].join('\n');

        // admin guide
        const platformGuides = ['admin-guide-entitlements.md', 'admin-guide-apps.md', 'admin-guide-operations.md', 'admin-guide-launch-flags.md']
            .filter((f) => existsSync(join(hubDir('layer', 'platform'), f)));
        out[`docs/okf/product/product/${id}/admin-guide.md`] = [
            ...head('admin guide', 'administrators who install, license and run it'),
            '## Install, licence and run', '',
            ...platformGuides.map((f) => `- [${titleIn('layer', 'platform', f)}](${link('layer', 'platform', f)})`),
            ...editions.map((e) => `- The ${editionLink(e)} Edition`), '',
            ...apps.flatMap((a) => {
                const g = guides(a, 'admin-guide');
                return [`## ${model.apps[a].title ?? a}`, '', ...(g.length ? g.map((x) => `- ${x}`) : [`- No admin guide in the hubs of this App's templates and Add-ons yet; see ${appLink(a)}.`]), ''];
            }),
            ...ownTemplateGuides('admin-guide'),
        ].join('\n');

        // The demo: its Space (the composed Space's parts are the Apps' templates), the Alert Rules those templates seed,
        // and the Demo Users and reset text of its presenter text (products/<id>.demo-build.txt).
        const demoTemplates = !p.demoSpace ? [] : p.demoSpace === p.space ? spaceParts(apps, model.apps).map((x) => x.template) : [p.demoSpace];
        const alerts = demoTemplates.flatMap((t) => {
            const d = join(root, 'spaces', '_templates', t, 'config', 'registry', 'alert-rules');
            return existsSync(d) ? readdirSync(d).filter((f) => f.endsWith('.toon')).sort().map((f) => {
                const r = parseToon(readFileSync(join(d, f), 'utf8'));
                const text = String(r.description ?? '').replace(/^"|"$/g, '');
                return { name: r.name ?? f.slice(0, -5), severity: r.severity ?? '', template: t, what: firstSentence(text).replace(/\|/g, '\\|') };
            }) : [];
        });
        // ...and those the demo's seed tool (tools/seed-<demoSpace>.mjs) adds over the control API: a POST to `.../alert-rules`
        // whose body starts `name: '<n>', severity: '<S>'` (la-showcase's `mule-pass-through`).
        const seedTool = p.demoSpace ? seedToolOf(p.demoSpace) : '';
        if (seedTool && existsSync(join(root, seedTool)))
            for (const [, n, sev] of readFileSync(join(root, seedTool), 'utf8').matchAll(/alert-rules`,\s*body:\s*\{\s*name:\s*'([^']+)',\s*severity:\s*'([A-Z]+)'/g))
                alerts.push({ name: n, severity: sev, template: '', seed: seedTool, what: `Added by the demo's seed (\`${seedTool}\`).` });
        const demoText = existsSync(join(root, demoTextOf(id))) ? readFileSync(join(root, demoTextOf(id)), 'utf8').split(/\r?\n/) : [];
        const userAt = demoText.findIndex((l) => /pick a Demo User:/.test(l));
        const demoUsers = [];
        for (let i = userAt + 1; userAt >= 0 && i < demoText.length && /^\s{4,}\S/.test(demoText[i]); i++) {
            const [user, display, ...role] = demoText[i].trim().split(/\s{2,}/);
            demoUsers.push({ user, display, role: role.join(' ') });
        }
        const resetAt = demoText.findIndex((l) => l.startsWith('RESET THE DEMO:'));
        const resetEnd = demoText.indexOf('', resetAt);
        const reset = resetAt < 0 ? '' : demoText.slice(resetAt, resetEnd < 0 ? undefined : resetEnd).join(' ').replace(/^RESET THE DEMO:\s*(.)/, (_, c) => c.toUpperCase());
        const navOf = (a) => appNav(model.apps[a]);
        const severityOrder = (s) => ['CRITICAL', 'HIGH', 'WARNING', 'MEDIUM', 'LOW', 'INFO'].indexOf(s) + 1 || 9;
        const alertsOf = (a) => alerts.filter((x) => templatesOf(a).includes(x.template));

        // demo script
        out[`docs/okf/product/product/${id}/brochure-demo-script.md`] = [
            ...head('demo script', 'presales and whoever runs a live demo'),
            ...(p.demoSpace ? [
                '## Before you start', '',
                `Run the **demo** Distribution: it signs people in as Demo Users with no password, on 127.0.0.1 only, over synthetic data. Never give it to a customer or use it with real data. The Space \`${p.demoSpace}\` is pre-installed with its seeded state; the presenter text \`${demoTextOf(id)}\` ships in the bundle.`, '',
                '1. Run `bin\\serve-demo.bat` (Windows) or `bin/serve-demo.sh` (Linux), then open http://127.0.0.1:8080.',
                '2. Pick a Demo User on the sign-in page (below).',
                ...(apps.length > 1 ? ['3. Move between the Apps with the App switcher at the top of the rail.'] : []), '',
            ] : [
                '## Before you start', '',
                `${name} has no demo Space: demo it on a trial or production install, over a Space you create from one of its Space Templates.`, '',
            ]),
            ...(demoUsers.length ? ['## Demo Users', '', '| Sign in as | Name | What they show |', '|---|---|---|', ...demoUsers.map((u) => `| \`${u.user}\` | ${u.display} | ${u.role.replace(/\|/g, '\\|')} |`), ''] : []),
            '## The walk-through', '',
            ...(p.brand?.signInTitle ? [`Open on the sign-in page: **${p.brand.signInTitle}**`, ''] : []),
            ...(apps.length ? apps.flatMap((a, i) => [
                `### ${i + 1}. ${appLink(a)}`, '',
                ...navOf(a).map((n) => `- **${n.label}**${n.blurb ? ` — ${n.blurb}` : ''}`),
                ...(alertsOf(a).length ? [`- Its Alert Rules:${alertsOf(a).map((x) => `\`${x.name}\``).join(', ')}.`] : []), '',
            ]) : ['No Apps: show the console over a Space created from one of its Space Templates.', '']),
            ...(alerts.length ? [
                '## The seeded Alerts', '',
                `The Alert Rules the demo Space holds: those its Space Templates ship and those the demo's seed adds. Show what they raised under **Alerts**.`, '',
                '| Alert Rule | Severity | From | What it finds |', '|---|---|---|---|',
                ...[...alerts].sort((x, y) => severityOrder(x.severity) - severityOrder(y.severity) || x.name.localeCompare(y.name)).map((x) => `| \`${x.name}\` | ${x.severity} | ${x.seed ? 'the seed' : packLink(x.template)} | ${x.what} |`), '',
            ] : []),
            '## Close', '',
            ...(p.brand?.tagline ? [`Say the tagline: *${p.brand.tagline}*`, ''] : []),
            `Editions: ${editions.map(editionLink).join(' · ')}. Distributions: ${list(p.distributions).join(', ')}. The [datasheet](features.md) says which Apps each Edition can carry.`, '',
            ...(reset ? ['## Reset', '', reset, ''] : []),
        ].join('\n');

        // video script: one overview video, in the beats of the hand-written series (module/la-core brochure-video-scripts.md)
        const shots = [
            ['Problem', p.brand?.tagline ? `*${p.brand.tagline}* over the raw records` : `${name} title card`, whatItIs],
            ...(p.brand?.signInTitle ? [['Sign in', `The sign-in page: **${p.brand.signInTitle}**${demoUsers.length ? `, the Demo Users listed` : ''}`, `${name}: ${p.brand.signInTitle}`]] : []),
            ...apps.map((a) => [model.apps[a].title ?? a, `${model.apps[a].title ?? a}: ${navOf(a).map((n) => `*${n.label}*`).join(', ') || 'its home page'}`, blurbs(a).join(' ') || `${model.apps[a].title ?? a}.`]),
            ...(alerts.length ? [['Outcome', `*Alerts*: what the demo Space's Alert Rules raised (${alerts.length} Alert Rules, ${alerts.filter((x) => x.severity === 'CRITICAL').length} of them critical)`, 'A finding raises an Alert, to be worked to a decision.']] : []),
            ...(p.demoSpace ? [['Explore it', `The Space \`${p.demoSpace}\` in the app, its home page`, `Everything shown is in the ${name} demo, over synthetic data: open it and repeat each step.`]] : []),
            ['Edition', `Editions: ${editions.map((e) => editionItems[e]?.title ?? e).join(' · ')}`, `${name} ships in the ${editions.map((e) => editionItems[e]?.title ?? e).join(', ').replace(/, ([^,]*)$/, ' and $1')} Editions.`],
        ];
        out[`docs/okf/product/product/${id}/brochure-video-script.md`] = [
            ...head('video script', 'marketing, presales and the video agency'),
            '## Brief', '',
            `- **Film on:** ${p.demoSpace ? `the demo Distribution, Space \`${p.demoSpace}\`` : 'a trial install, over a Space created from one of its Space Templates'}; a corner tag *Example · synthetic data* on every product shot.`,
            `- **Shows:** ${apps.length ? apps.map(appLink).join(', ') : 'the console'}.`,
            '- **Claims:** only what this script says; each line comes from the Product definition, its Apps and its demo Space. The [brochure](brochure.md) is the reference for anything wider.', '',
            '## Shots', '',
            '| # | Beat | On screen | Voice-over |', '|---|---|---|---|',
            ...shots.map(([beat, screen, voice], i) => `| ${i + 1} | ${beat} | ${screen.replace(/\|/g, '\\|')} | ${voice.replace(/\|/g, '\\|')} |`), '',
        ].join('\n');
    }
    return out;
}
