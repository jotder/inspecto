#!/usr/bin/env node
// render-component-shapes — the component shape reference page (COMPONENT-REFERENCE-GENERATED-1;
// docs/superpower/2026-11-20-agent-kit-ak2-plan.md §1.3).
//
//   node tools/render-component-shapes.mjs --write    rewrite the page
//   node tools/render-component-shapes.mjs --check    exit 1 when the page is stale, or a kind has no shape (CI)
//
// Two stages, each guarded:
//   1. docs/api/component-shapes/<kind>.json — one file per propose_change kind and per McpTools.COMPONENT_SHAPE_KINDS
//      component kind (COMPONENT-REFERENCE-MORE-KINDS-1), DERIVED from the code (the kinds' key
//      censuses, ConfigSpecs, the records the routes parse into, and the real parsers run over an example) by
//      features/inspecto-mcp ComponentShapesTest, which fails when a file is stale. Machine-readable: the AK-2 widening
//      plan's W5 serves each as the MCP Resource inspecto://shapes/{kind}.
//   2. docs/okf/product/module/config/api-component-shapes.md — this tool renders those files for people, with the
//      "Generated by" banner, so docs-health exempts it from its ratchets.
// --check also reads McpTools.CHANGE_ROUTES' and COMPONENT_SHAPE_KINDS' kinds from source, so a new kind without a shape
// fails here, before Maven runs.
// Tests: tools/render-component-shapes.test.mjs.

import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

export const SHAPES_DIR = 'docs/api/component-shapes';
export const PAGE = 'docs/okf/product/module/config/api-component-shapes.md';
export const MCP_TOOLS = 'features/inspecto-mcp/src/main/java/com/gamma/mcp/McpTools.java';
const REGEN = 'mvn -o test -pl features/inspecto-mcp -Dtest=ComponentShapesTest -Dshapes.write=true';

const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
const code = (v) => (v === undefined || v === null ? '' : '`' + (typeof v === 'string' ? v : JSON.stringify(v)) + '`');

/** The propose_change kinds McpTools.CHANGE_ROUTES names, read from its source (crud("k", …) and Map.entry("k", Map.of(…))). */
export function proposeKinds(src) {
    const start = src.indexOf('CHANGE_ROUTES = Map.ofEntries(');
    if (start < 0) throw new Error('McpTools.CHANGE_ROUTES not found');
    const end = src.indexOf(');\n', start);
    const block = src.slice(start, end);
    const kinds = new Set();
    for (const m of block.matchAll(/(?:crud\(|Map\.entry\()"([a-z0-9-]+)"/g)) kinds.add(m[1]);
    return [...kinds].sort();
}

/** The other component kinds with a shape: McpTools.COMPONENT_SHAPE_KINDS = Set.of("k", …), read from its source. */
export function componentShapeKinds(src) {
    const start = src.indexOf('COMPONENT_SHAPE_KINDS = Set.of(');
    if (start < 0) throw new Error('McpTools.COMPONENT_SHAPE_KINDS not found');
    const block = src.slice(start, src.indexOf(');', start));
    return [...block.matchAll(/"([a-z0-9-]+)"/g)].map((m) => m[1]).sort();
}

/** Every kind with a shape file: the propose_change kinds and the other component kinds, sorted. */
export function shapeKinds(src) {
    return [...new Set([...proposeKinds(src), ...componentShapeKinds(src)])].sort();
}

/** One shape (a kind's content, or one Entity List edit) as Markdown lines. */
export function renderShape(name, shape) {
    const L = [];
    if (name !== 'content') L.push(`#### \`${name}\``, '');
    L.push(`Keys from ${cell(shape.source)}. A key outside this list is **${shape.unknownKeys}**`
        + (shape.unknownKeys === 'refused' ? ` (422) — except an annotation named \`${shape.extensionPrefix}…\`, which is kept.`
            : shape.unknownKeys === 'kept' ? ' as sent.' : ' (nothing reads it).'), '');
    L.push('| Key | Type | Required | Default | Allowed values | Description |', '|---|---|---|---|---|---|');
    for (const f of shape.fields) {
        const req = f.setBy === 'server' ? 'set by the server' : f.required ? (f.requiredBy === 'parser' ? 'yes¹' : 'yes')
            : f.specRequired ? 'no²' : '';
        const values = f.values ? f.values.map((v) => '`' + v + '`').join(' ') : f.pattern ? `pattern ${code(f.pattern)}` : '';
        L.push(`| \`${f.path}\` | ${cell(f.type)} | ${req} | ${cell(code(f.default))} | ${cell(values)} | ${cell(f.description)} |`);
    }
    L.push('');
    for (const n of shape.notes ?? []) L.push(`- ${n}`);
    if (shape.notes?.length) L.push('');
    L.push('Example:', '', '```json', JSON.stringify(shape.example, null, 2), '```', '');
    return L;
}

/** The page, from the shape documents (kind → parsed JSON). */
export function renderPage(docs) {
    const kinds = Object.keys(docs).sort();
    const L = ['---', 'type: Reference', 'title: Component shape reference',
        'description: Every propose_change kind\'s content, and the other component kinds\' — keys, types, required or optional, defaults, allowed values and an example — derived from the code. Generated.',
        'resource: features/inspecto-mcp/src/test/java/com/gamma/mcp/ComponentShapesTest.java',
        'tags: [config, reference, shapes, agent, generated]', 'item: module.config', 'audience: internal', 'status: current',
        'code: features/inspecto-mcp', '---', '',
        '# Component shape reference', '',
        '> **Generated by `node tools/render-component-shapes.mjs`** from [`docs/api/component-shapes/`](../../../../api/component-shapes/),',
        `> which \`ComponentShapesTest\` (features/inspecto-mcp) derives from the code. Never edit by hand — regenerate with`,
        `> \`${REGEN}\` then \`node tools/render-component-shapes.mjs --write\`.`, '',
        'What each config kind an agent (or a person) proposes through `propose_change` may carry, so a draft is shaped right',
        'before it is sent instead of after a refusal, and the same for the component kinds `propose_change` does not offer',
        '(written through `/components/<type>`; their file says `proposeChange: false`). The same facts, one JSON file per',
        'kind, are in `docs/api/component-shapes/<kind>.json` and the MCP Resource `inspecto://shapes/<kind>`. A component kind',
        'with no shape is named, with why, in `ComponentShapesTest.UNSHAPED`.', '',
        'How the columns are derived: **keys** from the kind\'s key census in code, its `ConfigSpecs` fields or the record its',
        'route parses into; **type, description, allowed values** from the spec when there is one, else the record or the',
        'example; **required** because the real parser refuses the example without it — **yes** when the spec says so too,',
        '**yes¹** when only the parser does (so it may be required in the example\'s shape only), **no²** when the spec',
        'declares it required but the save does not refuse its absence; **default** from the spec, or what the parser fills',
        'in; **set by the server** for keys the server stamps or the store adds. These are the content',
        'checks of each save door without a Space: whether a named Dataset, Pipeline or Job exists is checked on save, and',
        'previewed with `validate_config`.', '',
    ];
    const index = (title, list) => {
        if (!list.length) return;
        L.push(`**${title}**`, '', '| Kind | Operations |', '|---|---|');
        for (const k of list) {
            const ops = Object.entries(docs[k].operations).map(([op, o]) => `\`${op}\` ${cell(o.route)}`).join(' · ');
            L.push(`| [\`${k}\`](#${k}) | ${ops} |`);
        }
        L.push('');
    };
    index('propose_change kinds', kinds.filter((k) => docs[k].proposeChange !== false));
    index('Other component kinds (not offered by propose_change)', kinds.filter((k) => docs[k].proposeChange === false));
    for (const k of kinds) {
        const d = docs[k];
        L.push(`## ${k}`, '');
        if (d.proposeChange === false) L.push('Not a `propose_change` kind: written through the component routes.', '');
        for (const [op, o] of Object.entries(d.operations))
            L.push(`- \`${op}\` → \`${o.route}\`` + (o.content ? (o.content === 'content' ? '' : ` — content: \`${o.content}\` below`) : ' — no content'));
        L.push('');
        for (const [name, shape] of Object.entries(d.shapes)) L.push(...renderShape(name, shape));
    }
    return L.join('\n').replace(/\n+$/, '\n');
}

/** Read every shape file under root. */
export function readShapes(root = '.') {
    const dir = join(root, SHAPES_DIR);
    const docs = {};
    if (!existsSync(dir)) return docs;
    for (const f of readdirSync(dir).filter((n) => n.endsWith('.json')).sort())
        docs[f.slice(0, -5)] = JSON.parse(readFileSync(join(dir, f), 'utf8'));
    return docs;
}

/** Problems: kinds (propose_change and the other shaped component kinds) without a shape file, and files of no such kind. */
export function coverage(kinds, docs) {
    const have = new Set(Object.keys(docs));
    return [...kinds.filter((k) => !have.has(k)).map((k) => `shape kind '${k}' has no ${SHAPES_DIR}/${k}.json`),
        ...[...have].filter((k) => !kinds.includes(k))
            .map((k) => `${SHAPES_DIR}/${k}.json names no propose_change kind and no COMPONENT_SHAPE_KINDS kind`)];
}

function main() {
    const mode = process.argv[2];
    if (!['--write', '--check'].includes(mode)) { console.error('usage: node tools/render-component-shapes.mjs --write | --check'); process.exit(2); }
    const docs = readShapes('.');
    const problems = coverage(shapeKinds(readFileSync(MCP_TOOLS, 'utf8')), docs);
    if (problems.length) {
        console.error(`✗ render-component-shapes: ${problems.join('; ')} — run ${REGEN}`);
        process.exit(1);
    }
    const text = renderPage(docs);
    const current = existsSync(PAGE) && readFileSync(PAGE, 'utf8').replace(/\r\n/g, '\n') === text;
    if (mode === '--write') {
        if (!current) writeFileSync(PAGE, text);
        console.log(`render-component-shapes: ${current ? 'page already current' : 'page rewritten'} (${Object.keys(docs).length} kinds)`);
        return;
    }
    if (!current) {
        console.error(`✗ render-component-shapes: ${PAGE} is stale; run node tools/render-component-shapes.mjs --write`);
        process.exit(1);
    }
    console.log(`✓ render-component-shapes: ${Object.keys(docs).length} kinds, page current`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
