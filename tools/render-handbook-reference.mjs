#!/usr/bin/env node
// render-handbook-reference — the Handbook's generated Reference pages (USER-HANDBOOK-1 P3;
// docs/superpower/2026-11-19-user-enablement-and-agent-kit-plan.md §3.2 "Reference (generated)", §4.2).
//
//   node tools/render-handbook-reference.mjs --write    rewrite the pages
//   node tools/render-handbook-reference.mjs --check    exit 1 when a page is stale (CI)
//
// Three pages in the layer/product hub, each a pure function of a contract, never edited by hand:
//   api-reference-http.md        every /api/v1 operation of docs/api/openapi-v1.json — method, path, summary — grouped by
//                                tag, with the editions that serve it: the first edition of the module whose code
//                                registers the route (tools/render-api-routes.mjs's scanner, the rule of its api-routes pages)
//   api-reference-editions.md    the edition matrix: every Product Map Item a customer meets (Products, Apps, Add-ons,
//                                Space Templates and industry packs, modules) × Basic / Standard / Advanced, from
//                                offerings/*.toon through tools/handbook-editions.mjs — the derivation the badges use
//   api-reference-vocabulary.md  the canonical terms of docs/GLOSSARY.md, each with its definition's first sentence;
//                                dated notes, board ids and links are dropped (the glossary stays the one home)
// Each opens with the "Generated by `node tools/…`" banner, so docs-health exempts it from its ratchets. The manifest
// places them in the `reference` chapter. Tests: tools/render-handbook-reference.test.mjs.

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { EDITIONS, SOLD, editionIndex, editionLabel, gatherFacts } from './handbook-editions.mjs';
import { gather as routeWorld, routeModules } from './render-api-routes.mjs';

export const HUB = 'docs/okf/product/layer/product';
export const PAGES = {
    http: `${HUB}/api-reference-http.md`,
    editions: `${HUB}/api-reference-editions.md`,
    vocabulary: `${HUB}/api-reference-vocabulary.md`,
};
const METHODS = ['get', 'put', 'post', 'patch', 'delete'];
/** The control-plane host module: serves the contract and every operation no other module registers. */
const HOST = 'processor';
const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
const banner = (from) => [`> **Generated by \`node tools/render-handbook-reference.mjs\`** from ${from}. Never edit by hand — change the`,
    '> source and run `node tools/render-handbook-reference.mjs --write`.'];
const front = (title, description) => ['---', 'type: Reference', `title: ${title}`, `description: ${description}`,
    'tags: [handbook, reference, generated]', '---', ''];

/** The HTTP API page. `opModule(METHOD, path)` names the module that registers the operation, or null; `moduleEdition(id)` its first edition. */
export function httpReference(openapi, opModule, moduleEdition) {
    const groups = new Map();
    let n = 0;
    for (const [path, byMethod] of Object.entries(openapi.paths ?? {})) {
        for (const m of METHODS) {
            const op = byMethod[m];
            if (!op) continue;
            n++;
            const tag = op.tags?.[0] ?? 'other';
            // Only a lower bound is a fact: an optional module's route has no code below that module's first edition.
            // A route a base module (or the host) registers can still need a later edition — the feature behind it,
            // a module it calls — so it gets no claim here (verification 2026-11-20: /access/policies, /assist).
            const mod = opModule(m.toUpperCase(), path);
            const ed = mod ? moduleEdition(mod) : null;
            const from = mod && ed !== EDITIONS[0] ? (ed && SOLD.includes(ed) ? `${ed} and up` : 'no sold edition') : '';
            if (!groups.has(tag)) groups.set(tag, []);
            groups.get(tag).push({ m: m.toUpperCase(), path, summary: op.summary ?? '', from });
        }
    }
    const L = [...front('HTTP API reference', 'Every Control API operation, by area. Generated.'),
        '# HTTP API reference', '', ...banner('[`docs/api/openapi-v1.json`](../../../../api/openapi-v1.json) and the modules that register each route'), '',
        `Every operation of the Control API — ${n} in ${groups.size} areas. Paths are relative to \`/api/v1\`; the full`,
        'contract (request and answer shapes, errors) is the OpenAPI document. *Not before* names the first edition whose',
        'build carries the code for the operation; below it the call is not found. An empty cell makes no promise: the',
        'feature behind the call may still need a later edition (see the edition matrix), and what a caller may do is',
        'decided by their Roles. Basic has no sign-in, so its calls carry no token.', ''];
    for (const tag of [...groups.keys()].sort((a, b) => a.localeCompare(b))) {
        L.push(`## ${cell(tag)}`, '', '| Method | Path | What it does | Not before |', '|---|---|---|---|');
        const rows = groups.get(tag).sort((a, b) => a.path.localeCompare(b.path) || METHODS.indexOf(a.m.toLowerCase()) - METHODS.indexOf(b.m.toLowerCase()));
        for (const r of rows) L.push(`| ${r.m} | \`${cell(r.path)}\` | ${cell(r.summary)} | ${r.from} |`);
        L.push('');
    }
    return L.join('\n');
}

const SECTIONS = [['product', 'Products'], ['app', 'Apps'], ['addon', 'Add-ons'], ['solution-pack', 'Space Templates and industry packs'], ['module', 'Modules']];

/** The edition matrix page over the Product Map `items` (key → Item) and `itemEdition(key)`. */
export function editionsReference(items, itemEdition) {
    const L = [...front('Edition matrix', 'What each edition carries — Products, Apps, Add-ons, Space Templates and modules. Generated.'),
        '# Edition matrix', '', ...banner('the Product Map (`product-map/`) and the Offerings (`offerings/*.toon`)'), '',
        'What each edition carries. The editions build on each other: Standard holds everything in Basic, Advanced',
        'everything in Standard. ✅ in the edition · — not in it. An item marked — everywhere ships in no sold edition',
        '(a demo build, an extra jar, or a preview). The same derivation puts the edition badge on every Handbook page.', ''];
    for (const [kind, title] of SECTIONS) {
        const rows = Object.entries(items).filter(([, it]) => it.kind === kind).sort(([, a], [, b]) => String(a.title).localeCompare(String(b.title)));
        if (!rows.length) continue;
        L.push(`## ${title}`, '', `| ${title.replace(/ and industry packs$/, '')} | ${SOLD.join(' | ')} |`, `|---|${SOLD.map(() => ':-:').join('|')}|`);
        for (const [key, it] of rows) {
            const e = itemEdition(key);
            const at = EDITIONS.indexOf(e);
            L.push(`| ${cell(it.title ?? key)} | ${SOLD.map((s) => (e && EDITIONS.indexOf(s) >= at ? '✅' : '—')).join(' | ')} |`);
        }
        L.push('');
    }
    return L.join('\n');
}

/** An italic dated note `*( … )*`, one level of parentheses inside. */
const NOTE = /\*\(([^()]|\([^()]*\))*\)\*/g;
/** A code span that names the repository, not the product: a Java package, a source file or doc path, a class. */
const REPO_CODE = /`(?:(?:com|org)\.[^`]*|[^`]*\.(?:md|java|ts|mjs|js)\b[^`]*|[^`]*\b(?:okf|docs|superpower)\/[^`]*|[A-Z][a-z0-9]+[A-Z][A-Za-z0-9]*(?:\.\w+)*(?:\(\))?)`/;

/** First sentence of a definition: dated notes, links, board ids and repository names dropped. */
export function firstSentence(text) {
    let s = text.replace(NOTE, '')                                          // *(added 2026-…)* notes
        .replace(/\[([^\]]+)\]\([^)]*\)/g, '$1')                            // links → their text
        .replace(/\s*\((?:[^()]*`?[A-Z][A-Z0-9]+(?:-[A-Z0-9]+)*-\d+`?[^()]*)\)/g, '')  // (… `BOARD-ID-1` …)
        .replace(/\s*\(([^()]|\([^()]*\))*\)/g, (p) => (REPO_CODE.test(p) || /\b(?:okf|docs|superpower)\//.test(p) ? '' : p))  // (… `com.x.Y` …)
        .replace(new RegExp(`\\s*(?:—\\s*)?${REPO_CODE.source}`, 'g'), '')  // a bare repository name
        .replace(/\s+/g, ' ').replace(/\s+([,.;:])/g, '$1').trim();
    // the first . ! ? that ends a sentence: outside parentheses and code, not an abbreviation, before a capital or the end
    let depth = 0, code = false;
    for (let i = 0; i < s.length; i++) {
        const c = s[i];
        if (c === '`') code = !code;
        else if (!code && c === '(') depth++;
        else if (!code && c === ')') depth = Math.max(0, depth - 1);
        else if (!code && depth === 0 && '.!?'.includes(c) && /^(\s+[A-Z*⛔⚠✅]|$)/.test(s.slice(i + 1)) && !/\b(e\.g|i\.e|etc|vs|incl|cf|approx)$/i.test(s.slice(0, i))) {
            return s.slice(0, i + 1);
        }
    }
    return s;
}

/**
 * The vocabulary page from GLOSSARY.md. A definition is a PARAGRAPH (after a blank line or a heading) that opens with a
 * head of bold names — `**Triage** / **Triage Run**`, `**Submission** (of a Regulatory Report)` — and any dated notes,
 * possibly wrapped over lines, then ` — ` and the definition. A bold word that merely wraps to a line start is inside
 * a paragraph and is not a term. A term is kept once, at its first definition, under its `## ` section.
 */
export function vocabularyReference(glossary) {
    const lines = glossary.replace(/\r\n/g, '\n').split('\n');
    const sections = [], seen = new Set();
    let cur = null;
    for (let i = 0; i < lines.length; i++) {
        const h = lines[i].match(/^## (.*)$/);
        if (h) { cur = { title: h[1].replace(NOTE, '').replace(/^[\d]+(-[A-Z])?\.\s*/, '').trim(), terms: [] }; sections.push(cur); continue; }
        const opens = /^\*\*[^*]/.test(lines[i]) && (i === 0 || !lines[i - 1].trim() || /^#/.test(lines[i - 1]));
        if (!opens || !cur) continue;
        const para = [lines[i]];
        while (i + 1 < lines.length && lines[i + 1].trim() && !/^(#|\||[-*] |>)/.test(lines[i + 1])) para.push(lines[++i]);
        const text = para.join(' ').replace(NOTE, '');
        const at = text.indexOf(' — ');
        if (at < 0) continue;
        const head = text.slice(0, at);
        // the head holds only bold names, slashes and plain parentheses — else the dash is inside a sentence
        if (head.replace(/\*\*[^*]+\*\*/g, '').replace(/\([^()]*\)/g, '').replace(/[\s/,]|\bor\b/g, '') !== '') continue;
        const term = head.replace(/\*\*/g, '').replace(/\s+/g, ' ').trim();
        const def = firstSentence(text.slice(at + 3));
        if (!def || seen.has(term.toLowerCase())) continue;
        seen.add(term.toLowerCase());
        cur.terms.push({ term, def });
    }
    const kept = sections.filter((s) => s.terms.length);
    const total = kept.reduce((n, s) => n + s.terms.length, 0);
    const L = [...front('Vocabulary', 'The canonical Inspecto terms, each in one sentence. Generated from the glossary.'),
        '# Vocabulary', '', ...banner('[`docs/GLOSSARY.md`](../../../../GLOSSARY.md)'), '',
        `The ${total} words Inspecto uses, each with the first sentence of its definition. One word names one thing, and`,
        'the console, the API and this Handbook use the same word.', ''];
    for (const s of kept) {
        L.push(`## ${s.title}`, '');
        for (const { term, def } of s.terms) L.push(`- **${term}** — ${def}`);
        L.push('');
    }
    return L.join('\n');
}

/** All three pages' text, keyed by repository path. */
export function renderAll(root = '.') {
    const facts = gatherFacts(root);
    const idx = editionIndex(facts);
    const world = routeWorld(root);
    const owners = routeModules(world);
    return {
        [PAGES.http]: httpReference(world.openapi, (m, p) => owners.get(`${m} ${p}`) ?? null, idx.module),
        [PAGES.editions]: editionsReference(facts.items, idx.item),
        [PAGES.vocabulary]: vocabularyReference(readFileSync(join(root, 'docs/GLOSSARY.md'), 'utf8')),
    };
}

function main() {
    const mode = process.argv[2];
    if (!['--write', '--check'].includes(mode)) { console.error('usage: node tools/render-handbook-reference.mjs --write | --check'); process.exit(2); }
    const pages = renderAll('.');
    const stale = Object.entries(pages).filter(([f, text]) => !existsSync(f) || readFileSync(f, 'utf8').replace(/\r\n/g, '\n') !== text);
    if (mode === '--write') {
        for (const [f, text] of stale) writeFileSync(f, text);
        console.log(`render-handbook-reference: ${stale.length} of ${Object.keys(pages).length} page(s) rewritten`);
        return;
    }
    if (stale.length) {
        console.error(`✗ render-handbook-reference: stale — ${stale.map(([f]) => f).join(', ')}; run node tools/render-handbook-reference.mjs --write`);
        process.exit(1);
    }
    console.log(`✓ render-handbook-reference: ${Object.keys(pages).length} generated Reference pages are current`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
