#!/usr/bin/env node
// render-product-hosts - write each Product's generated host data (PRODUCT-ASSEMBLY-1 PA-4).
//
//   node tools/render-product-hosts.mjs           write every host's product.generated.ts
//   node tools/render-product-hosts.mjs --check   exit 1 when one is stale (CI: the Product guard step)
//
// A Product's `host` names its Angular project (inspecto-ui/angular.json); the file lands in that project's
// `<sourceRoot>/app/product.generated.ts` and holds the brand and every App's nav in drawing order, from products/<id>.toon
// and apps/<app>/app.toon. The shell draws it when the server sends no resolved nav (a backend from before PA-3, a dev
// server with no descriptor) - see inspecto-ui/src/app/inspecto/product/product-host.ts. The text is written in the
// UI's Prettier style (.prettierrc.json: 4 spaces, single quotes, trailing commas, 120 columns), because CI runs
// `prettier --check` over the UI and this tool runs in a job with no npm dependencies.

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { checkModel, gatherModel, hostDataFile, productApps, productNavByApp } from './products.mjs';

const REPO = join(dirname(fileURLToPath(import.meta.url)), '..');
const NAV_FIELDS = ['app', 'id', 'path', 'label', 'icon', 'blurb', 'feature', 'capability'];

/** A TS string literal the way Prettier writes it: single quotes, unless that needs more escapes than double. */
function str(s) {
    const v = String(s);
    if (v.includes("'") && !v.includes('"')) return `"${v.replace(/\\/g, '\\\\')}"`;
    return `'${v.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}

/**
 * Where a Product's file goes: `<sourceRoot>/app/product.generated.ts` of its host when it is the host's default build,
 * `product.<id>.generated.ts` when it is built with a `hostConfiguration` (PA-5: la-app builds Inspecto LA and Inspecto
 * Telco; the configuration's fileReplacements swaps the file in).
 */
export function hostFile(projects, p) {
    const root = projects[p.host]?.sourceRoot;
    if (!root) throw new Error(`host '${p.host}' is not an Angular project with a sourceRoot in inspecto-ui/angular.json`);
    return join('inspecto-ui', root, ...hostDataFile(p).split('/'));
}

/**
 * The generated data of one Product: brand (name, the landing page's tagline and the sign-in pitch where it declares them),
 * its Apps in Product order (required first; the App switcher's fallback, PA-5b) and their nav, a page two Apps declare
 * drawn once under the first (productNavByApp, the rule the assembler's descriptor follows too).
 */
export function generatedProduct(model, p) {
    const { required, optional } = productApps(p);
    const ids = [...required, ...optional];
    const pitch = p.brand?.signInTitle && p.brand?.signInBody ? { title: p.brand.signInTitle, body: p.brand.signInBody } : null;
    const nav = productNavByApp(ids, model.apps).flatMap(({ app, entries }) =>
        entries.map((n) => Object.fromEntries(NAV_FIELDS.map((k) => [k, k === 'app' ? app : n[k]]).filter(([, v]) => v !== undefined && v !== ''))),
    );
    const brand = { name: p.brand?.name ?? p.title, ...(p.brand?.tagline ? { tagline: p.brand.tagline } : {}), ...(pitch ? { signInPitch: pitch } : {}) };
    return { id: p.id, title: p.title, brand, apps: ids.map((id) => ({ id, title: model.apps[id]?.title ?? id })), nav };
}

/**
 * One `key: 'value',` line at `pad`, as Prettier prints it at 120 columns: a line too long breaks after the colon, but only
 * for a key at least 7 wide (Prettier's short-key rule: `tabWidth` 4 + 3 of overlap), so `tagline:` breaks and `body:` never.
 */
function prop(pad, key, value) {
    const one = `${pad}${key}: ${str(value)},`;
    return one.length > 120 && key.length >= 7 ? [`${pad}${key}:`, `${pad}    ${str(value)},`] : [one];
}

/** The file text, in Prettier's output style for this shape (objects expanded one key per line). */
export function render(productFile, g) {
    const lines = [
        `// GENERATED by tools/render-product-hosts.mjs from ${productFile} and its Apps' app.toon - do not edit.`,
        '// Regenerate: node tools/render-product-hosts.mjs (CI checks it with --check).',
        "import type { GeneratedProduct } from '@inspecto/core/product/product-host';",
        '',
        'export const PRODUCT: GeneratedProduct = {',
        ...prop('    ', 'id', g.id),
        ...prop('    ', 'title', g.title),
        '    brand: {',
        ...prop('        ', 'name', g.brand.name),
    ];
    if (g.brand.tagline) lines.push(...prop('        ', 'tagline', g.brand.tagline));
    if (g.brand.signInPitch) {
        lines.push('        signInPitch: {', ...prop('            ', 'title', g.brand.signInPitch.title), ...prop('            ', 'body', g.brand.signInPitch.body), '        },');
    }
    lines.push('    },');
    // One App per line, objects kept inline (Prettier breaks an array of several objects, and keeps a lone one inline).
    const app = (a) => `{ id: ${str(a.id)}, title: ${str(a.title)} }`;
    if (!g.apps.length) lines.push('    apps: [],');
    else if (g.apps.length === 1) lines.push(`    apps: [${app(g.apps[0])}],`);
    else lines.push('    apps: [', ...g.apps.map((a) => `        ${app(a)},`), '    ],');
    if (!g.nav.length) lines.push('    nav: [],');
    else {
        lines.push('    nav: [');
        for (const n of g.nav) {
            lines.push('        {');
            for (const [k, v] of Object.entries(n)) lines.push(...prop('            ', k, v));
            lines.push('        },');
        }
        lines.push('    ],');
    }
    lines.push('};', '');
    return lines.join('\n');
}

/** Every host file this repo's Products produce: [{ product, file, text }]. Throws on broken definitions (two default builds of one host among them). */
export function renderAll(root = REPO) {
    const model = gatherModel(root);
    const findings = checkModel(model);
    if (findings.length) throw new Error(`the definitions do not pass tools/check-products.mjs:\n  ${findings.join('\n  ')}`);
    return Object.entries(model.products).map(([id, p]) => ({
        product: id,
        file: hostFile(model.ngProjects, p),
        text: render(`products/${id}.toon`, generatedProduct(model, p)),
    }));
}

function main() {
    const check = process.argv.includes('--check');
    try {
        const stale = [];
        for (const { product, file, text } of renderAll()) {
            const path = join(REPO, file);
            const now = existsSync(path) ? readFileSync(path, 'utf8').replace(/\r\n/g, '\n') : null;
            if (now === text) continue;
            if (check) stale.push(`${file} (Product '${product}')`);
            else { writeFileSync(path, text); console.log(`render-product-hosts: wrote ${file}`); }
        }
        if (stale.length) {
            console.error(`render-product-hosts: stale - run: node tools/render-product-hosts.mjs\n  ${stale.join('\n  ')}`);
            process.exit(1);
        }
        if (check) console.log('render-product-hosts: every host file is current');
    } catch (e) {
        console.error(`render-product-hosts: ${e.message}`);
        process.exit(1);
    }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
